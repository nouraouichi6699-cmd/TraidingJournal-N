/**
 * Builds the static world map that the loading screen draws, so the app itself needs no geo library.
 *
 * Run it only when the map has to change:
 *
 *   npm i --no-save d3-geo topojson-client world-atlas
 *   node tools/build-world-map.mjs
 *   npm i            # drops the three again, they are not dependencies
 *
 * It takes Natural Earth 110m country shapes, drops Antarctica, merges what is left into one landmass (so no
 * internal borders are drawn), projects it with geoNaturalEarth1 and writes src/components/worldMap.ts: the land
 * path, the view box fitted tightly around it, and the cities projected into that same space.
 */
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature, merge } from "topojson-client";

const require = createRequire(import.meta.url);
const WIDTH = 1000; // the view box width; the height follows from the projected land
const ANTARCTICA = "Antarctica";

// Longitude and latitude of each city, with the colour group it is drawn in and the session it follows. Sydney is
// drawn in the Asian colour but keeps its own session, which is why the two are separate fields.
const CITIES = [
  { id: "london", lon: -0.1276, lat: 51.5072, group: "eu", session: "sessLN" },
  { id: "frankfurt", lon: 8.6821, lat: 50.1109, group: "eu", session: "sessLN" },
  { id: "paris", lon: 2.3522, lat: 48.8566, group: "eu", session: "sessLN" },
  { id: "zurich", lon: 8.5417, lat: 47.3769, group: "eu", session: "sessLN" },
  { id: "newYork", lon: -74.006, lat: 40.7128, group: "am", session: "sessNY" },
  { id: "chicago", lon: -87.6298, lat: 41.8781, group: "am", session: "sessNY" },
  { id: "toronto", lon: -79.3832, lat: 43.6532, group: "am", session: "sessNY" },
  { id: "tokyo", lon: 139.6917, lat: 35.6895, group: "as", session: "sessTK" },
  { id: "hongKong", lon: 114.1694, lat: 22.3193, group: "as", session: "sessTK" },
  { id: "shanghai", lon: 121.4737, lat: 31.2304, group: "as", session: "sessTK" },
  { id: "singapore", lon: 103.8198, lat: 1.3521, group: "as", session: "sessTK" },
  { id: "dubai", lon: 55.2708, lat: 25.2048, group: "as", session: "sessTK" },
  { id: "sydney", lon: 151.2093, lat: -33.8688, group: "as", session: "sessSY" },
];

const topo = require("world-atlas/countries-110m.json");
const geoms = topo.objects.countries.geometries.filter((g) => g.properties?.name !== ANTARCTICA);
if (geoms.length === topo.objects.countries.geometries.length) throw new Error("Antarctica was not found: check the data");
// merge() dissolves the shared borders, which leaves the coastline as the only line to stroke.
const land = { type: "MultiPolygon", coordinates: merge(topo, geoms).coordinates };

const proj = geoNaturalEarth1();
proj.fitWidth(WIDTH, land);
// Shift the projection so the land sits flush in the corner, and the view box carries no empty margin.
const rough = geoPath(proj);
const [[x0, y0], [x1, y1]] = rough.bounds(land);
const [tx, ty] = proj.translate();
proj.translate([tx - x0, ty - y0]);

const path = geoPath(proj);
// One decimal is finer than a screen pixel at this width and keeps the string small.
if (typeof path.digits === "function") path.digits(1);
const d = path(land);
const round = (n) => Math.round(n * 10) / 10;
const width = round(x1 - x0);
const height = round(y1 - y0);

const cities = CITIES.map((c) => {
  const p = proj([c.lon, c.lat]);
  if (!p) throw new Error(`${c.id} does not project`);
  return { id: c.id, x: round(p[0]), y: round(p[1]), group: c.group, session: c.session };
});

const out = `// Generated by tools/build-world-map.mjs from Natural Earth 110m (world-atlas), Antarctica removed,
// merged into one landmass and projected with d3 geoNaturalEarth1. Do not edit by hand: run the script instead.

/** The whole landmass as one path, in the coordinates of VIEW_BOX. */
export const WORLD_PATH =
  "${d}";

export const VIEW_BOX = "0 0 ${width} ${height}";
export const MAP_W = ${width};
export const MAP_H = ${height};

/** Which colour a city is drawn in: Europe, the Americas, Asia. */
export type CityGroup = "eu" | "am" | "as";

export interface City {
  id: string;
  x: number;
  y: number;
  group: CityGroup;
  /** The session whose hours light this city, as an i18n key. */
  session: "sessLN" | "sessNY" | "sessTK" | "sessSY";
}

export const CITIES: City[] = ${JSON.stringify(cities, null, 2).replace(/"(id|x|y|group|session)":/g, "$1:")};
`;

const dest = process.argv[2] ?? new URL("../src/components/worldMap.ts", import.meta.url);
writeFileSync(dest, out);
console.log(`land path: ${d.length} chars · view box ${width}x${height} · ${cities.length} cities`);
