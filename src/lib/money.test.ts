import { commonCurrency, currencySymbol, fmtMoney, ltrNumbers } from "./money";
let pass = 0, fail = 0;
const eq = (name: string, got: unknown, exp: unknown) => { const ok = got === exp; ok ? pass++ : fail++; console.log(`${ok ? "PASS" : "FAIL"}  ${name}${ok ? "" : `  got ${JSON.stringify(got)}, expected ${JSON.stringify(exp)}`}`); };
eq("summary: 10,000.00 -> 10,000$", fmtMoney(10000, { currency: "USD" }), "10,000$");
eq("summary rounds: 1,705.67 -> 1,706$", fmtMoney(1705.67, { currency: "USD" }), "1,706$");
eq("summary rounds half away from zero: 2.5 -> 3$", fmtMoney(2.5, { currency: "USD" }), "3$");
eq("summary negative: -1,389.90 -> -1,390$", fmtMoney(-1389.9, { currency: "USD" }), "-1,390$");
eq("summary sign: +6,000$", fmtMoney(6000, { currency: "USD", sign: true }), "+6,000$");
eq("trade row keeps cents: 18.16$", fmtMoney(18.16, { cents: true, currency: "USD" }), "18.16$");
eq("trade row signed: +94.52$", fmtMoney(94.52, { cents: true, sign: true, currency: "USD" }), "+94.52$");
eq("trade row negative: -40.00$", fmtMoney(-40, { cents: true, currency: "USD" }), "-40.00$");
eq("no negative zero: -0.4 -> 0$", fmtMoney(-0.4, { currency: "USD", sign: true }), "0$");
eq("no negative zero with cents: -0.004 -> 0.00$", fmtMoney(-0.004, { cents: true, currency: "USD" }), "0.00$");
eq("euro symbol", fmtMoney(1234.4, { currency: "eur" }), "1,234€");
eq("code without symbol gets a space", fmtMoney(250, { currency: "TND" }), "250 TND");
eq("mixed currencies: no symbol", fmtMoney(99928, { currency: null }), "99,928");
eq("not finite -> '-'", fmtMoney(NaN), "-");
eq("currencySymbol(USD)", currencySymbol("USD"), "$");
eq("commonCurrency same", commonCurrency([{ currency: "USD" }, { currency: "usd" }]), "USD");
eq("commonCurrency mixed -> null", commonCurrency([{ currency: "USD" }, { currency: "EUR" }]), null);
eq("commonCurrency none -> null", commonCurrency([]), null);
console.log("-- ltrNumbers (Arabic text)");
const I = (x: string) => `\u2066${x}\u2069`;
eq("money keeps its sign and suffix", ltrNumbers("متوسط 59$ · -87$"), `متوسط ${I("59$")} · ${I("-87$")}`);
eq("percent, R and hour units", ltrNumbers("نسبة 38.6% · +0.11R · 14h"), `نسبة ${I("38.6%")} · ${I("+0.11R")} · ${I("14h")}`);
eq("currency code after a space", ltrNumbers("الرصيد 1,234 TND"), `الرصيد ${I("1,234 TND")}`);
eq("digits inside a symbol name untouched", ltrNumbers("NAS100 US30"), "NAS100 US30");
eq("a date stays one piece", ltrNumbers("يوم 2025-06-20"), `يوم ${I("2025-06-20")}`);
eq("sentence period stays outside", ltrNumbers("حتى 59."), `حتى ${I("59")}.`);
eq("applying twice changes nothing", ltrNumbers(ltrNumbers("متوسط -87$ · 38.6%")), ltrNumbers("متوسط -87$ · 38.6%"));
eq("no numbers: unchanged", ltrNumbers("بعد خسارة"), "بعد خسارة");
console.log(`\n${pass} passed, ${fail} failed`); process.exit(fail ? 1 : 0);
